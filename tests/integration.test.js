const client = () => {
  const cookies = new Map();
  const request = async (route, method = "GET", body, expected = 200, extraHeaders = {}) => {
    const multipart = body instanceof FormData;
    const response = await fetch(base + route, { method, headers: { ...(cookies.size ? { Cookie: [...cookies].map(([k,v])=>`${k}=${v}`).join('; ') } : {}), ...(!multipart && body ? { "Content-Type": "application/json" } : {}), ...extraHeaders }, body: body === undefined ? undefined : multipart ? body : JSON.stringify(body) });
    for (const value of response.headers.getSetCookie()) {
      const [pair] = value.split(';'); const index = pair.indexOf('='); const name=pair.slice(0,index), cookie=pair.slice(index+1);
      if (!cookie) cookies.delete(name); else cookies.set(name,cookie);
    }
    const result = await response.json();
    assert.equal(response.status, expected, `${method} ${route}: ${JSON.stringify(result)}`);
    return result;
  };
  request.cookies = () => new Map(cookies);
  return request;
};
